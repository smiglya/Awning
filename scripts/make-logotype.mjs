import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { openFont } from './lib/ttf-glyphs.mjs'
import { parseSvg, inkBounds } from './lib/svg-raster.mjs'

/**
 * Regenerates brand/awning-logotype.svg: the mark, then "wning" as outlines.
 *
 * A design tool, run by hand — not part of `npm run build`, and it needs a font
 * file the repo does not carry:
 *
 *   node scripts/make-logotype.mjs path/to/InterDisplay-Medium.ttf
 *
 * Get it from github.com/rsms/inter/releases (Inter is under the SIL Open Font
 * License, which permits using the typeface to make artwork like this).
 *
 * Why generate rather than draw. The hand-assembled lockup this replaces had
 * three baselines (293.848, 296.016, 294.692), three x-heights, letter gaps of
 * 192/151/127/151, and an 'i' from a slab typeface sitting between geometric
 * neighbours. Every one of those is a metric the font already gets right, so
 * take them from the font instead of re-deciding them by eye.
 *
 * Inter Display rather than Inter: it is the optical size cut for large text,
 * which is what a logotype is. The site's body copy stays on Inter proper.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const WORD = 'wning'

/**
 * The mark stands in for the capital A, so its height sets the cap height and
 * everything else follows from the font's own proportions.
 */
const MARK_SCALE = 22.515

/**
 * Space between the mark and the w, in font units. Hand-set, because the mark's
 * right side is a receding diagonal rather than a stem: the metric sidebearing
 * a font would apply leaves a hole that reads as a word break.
 */
const MARK_GAP = 190

/**
 * Extra letterspacing, in font units per em of 2048. Zero — Inter Display is
 * already spaced for display sizes, and tightening a five-letter word further
 * is how logotypes end up with the letters touching at small sizes.
 */
const TRACKING = 0

const round = (n) => Number(n.toFixed(2))

/** logo.svg is all straight segments, so it converts to scaled path data exactly. */
function markPath(scale, shift) {
  const { shapes } = parseSvg(readFileSync(join(root, 'brand/logo.svg'), 'utf8'))
  if (shapes.length !== 1) throw new Error('logo.svg should hold exactly one shape')
  return shapes[0]
    .map((ring) => {
      const points = ring.map(
        ([x, y]) => `${round(x * scale + shift.x)} ${round(y * scale + shift.y)}`
      )
      return `M${points[0]}${points
        .slice(1)
        .map((p) => `L${p}`)
        .join('')}Z`
    })
    .join('')
}

function build(fontPath, shift = { x: 0, y: 0 }) {
  const font = openFont(readFileSync(fontPath))
  if (font.capHeight === null) throw new Error('font has no OS/2 cap height')

  // The mark is 13 units tall in logo.svg, so its output height is 13*MARK_SCALE.
  // Scale the font so its cap height lands exactly there: the mark is the A, and
  // an A that does not share the cap line is the first thing anyone notices.
  const k = (13 * MARK_SCALE) / font.capHeight

  const baseline = 13 * MARK_SCALE
  let pen = 12 * MARK_SCALE + MARK_GAP * k

  const paths = [markPath(MARK_SCALE, shift)]

  for (const character of WORD) {
    const originX = pen
    // font units are y-up from the baseline; SVG is y-down from the top
    const { advance, path } = font.glyph(character, (x, y) => [
      originX + x * k + shift.x,
      baseline - y * k + shift.y,
    ])
    if (path) paths.push(path)
    pen += (advance + TRACKING) * k
  }

  return paths
}

function measure(paths) {
  const probe = `<svg>${paths.map((d) => `<path d="${d}"/>`).join('')}</svg>`
  return inkBounds(parseSvg(probe).shapes)
}

/**
 * Builds twice: once to find where the ink actually falls, then again shifted so
 * it starts at the origin. The lockup does not sit neatly inside the mark's box —
 * the i's dot rises above the cap line, because in Inter, as in most faces,
 * ascenders are taller than capitals. Cropping that would be wrong and padding
 * for it would put slack in the viewBox, so move the whole thing instead.
 */
function tighten(fontPath) {
  const first = measure(build(fontPath))
  const shift = { x: -first.minX, y: -first.minY }
  const paths = build(fontPath, shift)
  const bounds = measure(paths)
  return { paths, width: round(bounds.maxX), height: round(bounds.maxY) }
}

const fontPath = process.argv[2]
if (!fontPath) {
  console.error('usage: node scripts/make-logotype.mjs <path to a .ttf>')
  process.exit(1)
}

const { paths, width, height } = tighten(fontPath)

const svg = `<!-- Awning logotype: the mark, then the name as outlines.

     Generated by scripts/make-logotype.mjs — edit that, not this. The name is
     set in Inter Display (SIL Open Font License), the display cut of the
     typeface the site itself uses, with the mark standing in for the capital A.
     Cap height, x-height, sidebearings and letter spacing all come from the
     font's own metrics rather than being decided by eye.

     viewBox is tight to the ink so no empty space travels with the artwork.
     fill is currentColor so the lockup can reverse out of a dark surface.

     Mirrored as JSX in src/components/Brand.tsx; tests/brand.test.ts fails if
     the two ever disagree. -->
<svg
  xmlns="http://www.w3.org/2000/svg"
  viewBox="0 0 ${width} ${height}"
  width="${width}"
  height="${height}"
  fill="currentColor"
>
${paths.map((d) => `  <path d="${d}" />`).join('\n')}
</svg>
`

writeFileSync(join(root, 'brand/awning-logotype.svg'), svg)
console.log(`brand/awning-logotype.svg  ${width} x ${height}  ${paths.length} paths`)
