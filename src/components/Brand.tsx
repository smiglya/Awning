/**
 * The mark and the logotype, inline.
 *
 * Inline rather than <img src="/logo.svg"> for three reasons: they inherit
 * `color`, so the same lockup works on paper and reversed out of ink; they are
 * present in the prerendered HTML instead of arriving one request later; and the
 * prerender has no browser to fetch anything with.
 *
 * The geometry is copied verbatim from brand/logo.svg and
 * brand/awning-logotype.svg, which stay the source of truth for designers and
 * for the Open Graph card. tests/brand.test.ts fails if the two ever disagree —
 * a silent copy is exactly how a logo ends up half-updated.
 *
 * Both are aria-hidden. They carry no information a screen reader needs beyond
 * the brand name, which the surrounding markup provides as text.
 */

